import { mkdir, readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { parseCatalogIndex, resolveCatalogPath } from "@rendyn/catalog";

const projectRoot = resolve(import.meta.dirname, "..");
const catalogRoot = resolve(projectRoot, "catalog");
const outputPath = resolve(projectRoot, "apps/api/src/generated/catalog-data.ts");

async function readOptional(path: string): Promise<string | undefined> {
  try {
    return await readFile(path, "utf8");
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === "ENOENT") return undefined;
    throw error;
  }
}

async function generate(): Promise<string> {
  const rawIndex = await readFile(resolveCatalogPath(catalogRoot, "index.json"), "utf8");
  const index = parseCatalogIndex(JSON.parse(rawIndex));
  const components: Record<string, unknown> = {};
  const licenses: Record<string, string> = {};

  for (const component of index.components) {
    const raw = await readFile(resolveCatalogPath(catalogRoot, component.manifestPath), "utf8");
    components[component.manifestPath] = JSON.parse(raw);
  }
  for (const source of index.sources) {
    licenses[source.license.textPath] = await readFile(
      resolveCatalogPath(catalogRoot, source.license.textPath),
      "utf8",
    );
  }

  const snapshot = {
    rawIndex,
    components,
    licenses,
    rawEmbeddings: await readOptional(resolveCatalogPath(catalogRoot, "embeddings.json")),
  };

  return [
    "// Generated by scripts/generate-worker-catalog.ts. Do not edit by hand.",
    'import type { CatalogSnapshot } from "@rendyn/catalog";',
    `export const catalogSnapshot: CatalogSnapshot = ${JSON.stringify(snapshot)};`,
    "",
  ].join("\n");
}

const expected = await generate();
if (process.argv.includes("--check")) {
  const current = await readOptional(outputPath);
  if (current !== expected) {
    throw new Error("Worker catalogue snapshot is missing or stale; run pnpm catalog:worker:generate");
  }
  console.log("Worker catalogue snapshot is current");
} else {
  await mkdir(resolve(outputPath, ".."), { recursive: true });
  await writeFile(outputPath, expected);
  console.log(`Wrote ${outputPath}`);
}
